/// Pastes text into the focused app: puts it on the clipboard, sends ⌘V and then
/// puts the previous clipboard contents back.
///
/// ⌘V goes out as a real key chord (SyntheticKeyboard.swift). A remote desktop client
/// (RemoteSession.swift) gets slower chord timing, the clipboard sync before the paste
/// (RemoteClipboardSync.swift) and more time before the clipboard is restored.
@MainActor
public final class PasteboardTextInserter: TextInserting {
    /// Tells clipboard managers to skip the dictated text (nspasteboard.org).
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private static let logger = Logger(subsystem: "de.foxagon.pavarotti", category: "Paste")

    private let pasteboard: NSPasteboard
    private let trust: any AccessibilityTrust
    private let system: PasteSystem
    private let nudger: RemoteClipboardSyncNudger

    public convenience init(trust: any AccessibilityTrust) {
        self.init(
            trust: trust,
            system: .live,
            nudger: RemoteClipboardSyncNudger(environment: SystemRemoteClipboardSyncEnvironment())
        )
    }

    init(
        pasteboard: NSPasteboard = .general,
        trust: any AccessibilityTrust,
        system: PasteSystem,
        nudger: RemoteClipboardSyncNudger
    ) {
        self.pasteboard = pasteboard
        self.trust = trust
        self.system = system
        self.nudger = nudger
    }

    public func insert(_ text: String, restoringClipboard: Bool) async -> TextInsertionResult {
        let payload = ClipboardPayload(text: text, restoresClipboard: restoringClipboard, pasteboard: pasteboard)
        guard trust.isTrusted else {
            // Leave the text on the clipboard so it can be pasted by hand.
            payload.write()
            return .copiedOnly
        }
        let target = system.frontmostBundleIdentifier()
        let remote = RemoteSessionClassifier.classify(
            bundleIdentifier: target,
            additionalBundleIdentifiers: system.additionalRemoteBundleIdentifiers()
        )
        guard let remote else {
            payload.write()
            await postPasteShortcut(timing: .local)
            await restore(payload, after: system.restoreDelay)
            return .pasted
        }
        return await insertRemotely(payload, target: target, kind: remote)
    }

    // MARK: - Remote desktops

    private enum RemoteSyncResult {
        case paste
        /// No paste. The text is on the clipboard unless it changed meanwhile.
        case skip(PasteSkipReason)
        case cancelled
    }

    private func insertRemotely(
        _ payload: ClipboardPayload,
        target: String?,
        kind: RemoteSessionKind
    ) async -> TextInsertionResult {
        switch await syncClipboard(payload, target: target) {
        case .paste:
            await postPasteShortcut(timing: .remote)
            await restore(payload, after: system.remoteRestoreDelay)
            return .pasted
        case let .skip(reason):
            Self.logger.warning(
                "Remote paste skipped: target=\(target ?? "nil", privacy: .public), kind=\(kind.rawValue, privacy: .public), reason=\(String(describing: reason), privacy: .public)"
            )
            return .notPasted(reason)
        case .cancelled:
            payload.restoreIfOnClipboard()
            return .notPasted(.cancelled)
        }
    }

    /// Lets the remote desktop client send the text to the remote computer: the nudge writes
    /// it while Pavarotti is active. If the clipboard changed by the time the remote window is
    /// back, the text is written again during a second nudge, and only a second change skips
    /// the paste. A disabled or unavailable nudge writes the text and pastes as before.
    private func syncClipboard(_ payload: ClipboardPayload, target: String?) async -> RemoteSyncResult {
        for attempt in 1 ... 2 {
            let outcome = await nudger.nudge(expectedBundleIdentifier: target) {
                payload.write()
            }
            if let result = decide(outcome, payload: payload, isLastAttempt: attempt == 2) {
                return result
            }
            Self.logger.warning("The clipboard changed during the clipboard sync; writing the text again and repeating the sync once")
        }
        return .skip(.clipboardChanged)
    }

    /// What a nudge means for the paste. `nil` repeats the nudge.
    private func decide(
        _ outcome: RemoteClipboardSyncNudgeOutcome,
        payload: ClipboardPayload,
        isLastAttempt: Bool
    ) -> RemoteSyncResult? {
        switch outcome {
        case .disabled, .unavailable, .skippedForRegularActivationPolicy:
            payload.writeUnlessOnClipboard()
            return .paste
        case .frontmostApplicationChanged:
            // The text goes on the clipboard for pasting by hand.
            payload.writeUnlessOnClipboard()
            return .skip(.remoteWindowNotInFront)
        case .cancelled:
            return .cancelled
        case let .nudged(remote):
            guard nudger.isFrontmost(remote) else { return .skip(.remoteWindowNotInFront) }
            if payload.isOnClipboard {
                return .paste
            }
            return isLastAttempt ? .skip(.clipboardChanged) : nil
        }
    }

    // MARK: - Posting and restoring

    private func postPasteShortcut(timing: SyntheticChordTiming) async {
        let settings = system.keyboardSettings()
        let key = CGKeyCode(kVK_ANSI_V)
        let posted = if settings.chordEnabled {
            await system.poster.post(
                SyntheticKeyEvent.commandChord(keyCode: key, timing: timing),
                options: .pasteChord(settings: settings, keyboardType: system.keyboardType())
            )
        } else {
            await system.poster.post(SyntheticKeyEvent.flagsOnly(keyCode: key), options: .flagsOnlyPaste)
        }
        if !posted {
            Self.logger.error("The paste shortcut could not be posted")
        }
    }

    /// Puts the user's clipboard back after `delay`, while the clipboard still holds the text.
    /// The pause is not cut short by cancelling: the target app may still be reading the text.
    private func restore(_ payload: ClipboardPayload, after delay: Duration) async {
        guard payload.hasSavedClipboard else { return }
        let pause = system.sleep
        _ = await Task { @MainActor in
            try await pause(delay)
        }.result
        payload.restoreIfOnClipboard()
    }
}

/// What the inserter reads from and posts to the system. Tests replace each part.
struct PasteSystem {
    var poster: any SyntheticKeyEventPosting
    /// The bundle identifier of the frontmost app, which receives the paste.
    var frontmostBundleIdentifier: @MainActor () -> String?
    var keyboardSettings: () -> SyntheticKeyboardSettings
    var additionalRemoteBundleIdentifiers: () -> [String]
    var keyboardType: () -> Int64?
    /// How long the target app gets to read the clipboard before it is restored.
    var restoreDelay = Duration.milliseconds(400)
    /// Remote desktop clients send the clipboard over the network first.
    var remoteRestoreDelay = Duration.milliseconds(1500)
    var sleep: @MainActor @Sendable (Duration) async throws -> Void = { try await Task.sleep(for: $0) }

    static var live: PasteSystem {
        PasteSystem(
            poster: CGEventKeyPoster(),
            frontmostBundleIdentifier: { NSWorkspace.shared.frontmostApplication?.bundleIdentifier },
            keyboardSettings: { SyntheticKeyboardSettings.load(from: .standard) },
            additionalRemoteBundleIdentifiers: { RemoteSessionClassifier.additionalBundleIdentifiers(from: .standard) },
            keyboardType: { Int64(LMGetKbdType()) }
        )
    }
}

/// The dictated text on its way to the clipboard, with the user's clipboard from just before
/// the first write.
@MainActor
final class ClipboardPayload {
    let text: String
    let restoresClipboard: Bool
    private let pasteboard: NSPasteboard
    private var saved: PasteboardSnapshot?
    /// The clipboard's change count right after the text was written, `nil` before.
    private var owned: Int?

    init(text: String, restoresClipboard: Bool, pasteboard: NSPasteboard) {
        self.text = text
        self.restoresClipboard = restoresClipboard
        self.pasteboard = pasteboard
    }

    /// Whether the clipboard still holds the text written last.
    var isOnClipboard: Bool {
        owned == pasteboard.changeCount
    }

    var hasSavedClipboard: Bool {
        saved != nil
    }

    /// Writes the text. The first write saves the user's clipboard; during a remote paste
    /// that includes what the remote client sent when its window lost focus.
    func write() {
        if restoresClipboard, saved == nil {
            saved = PasteboardSnapshot(of: pasteboard)
        }
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: PasteboardTextInserter.transientType)
        item.setData(Data(), forType: PasteboardTextInserter.autoGeneratedType)
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        owned = pasteboard.changeCount
    }

    func writeUnlessOnClipboard() {
        if !isOnClipboard {
            write()
        }
    }

    /// Puts the user's clipboard back, unless something else wrote to the clipboard since.
    func restoreIfOnClipboard() {
        guard isOnClipboard, let saved else { return }
        saved.restore(to: pasteboard)
    }
}

/// A copy of every item and type on a pasteboard.
struct PasteboardSnapshot {
    let items: [[NSPasteboard.PasteboardType: Data]]

    @MainActor
    init(of pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            var entries: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    entries[type] = data
                }
            }
            return entries
        }
    }

    @MainActor
    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries {
                item.setData(data, forType: type)
            }
            return item
        }
        if !restored.isEmpty {
            pasteboard.writeObjects(restored)
        }
    }
}

/// Accessibility access through `AXIsProcessTrusted`.
@MainActor
public final class SystemAccessibilityTrust: AccessibilityTrust {
    public init() {}

    public var isTrusted: Bool {
        AXIsProcessTrusted()
    }

    public func requestTrust() {
        // The key behind kAXTrustedCheckOptionPrompt, spelled out because the imported
        // global is not concurrency-safe in Swift 6.
        let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    /// Opens System Settings at Privacy & Security → Accessibility.
    public static func openSettings() {
        guard let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") else {
            return
        }
        NSWorkspace.shared.open(url)
    }
}
